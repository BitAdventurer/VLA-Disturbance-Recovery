#!/usr/bin/env python3
"""table_pertask.py PAPERDIR: per-task success table (tables/res_pertask.tex) and the episode-level / failure analysis
numbers (figures/res_analysis.json) for the ICEIC residual paper, computed from the raw result files.
Base = 7 noise draws of (2,10); detector replan = 5 draws; student v2 = 5 draws; all 500 disturbed episodes."""
import json
import os
import sys

import numpy as np

E = os.path.expanduser(os.environ.get("VLA_EXPERIMENTS", "~/disk2/vla-inference-scheduling/experiments"))
OUT = sys.argv[1]


def L(p):
    return {(r["task_id"], r["init_state_id"]): r for r in map(json.loads, open(p)) if "success" in r and not r.get("error")}


pool = [L("%s/results_dist/obj_static_n2_h10_%s.jsonl" % (E, s)) for s in ("s0", "ns1_s0", "ns2_s0", "ns3_s0", "ns4_s0", "ns5_s0", "ns6_s0")]
det = [L("%s/results_dist/det_n2h10_%s.jsonl" % (E, s)) for s in ("s0", "ns1_s0", "ns2_s0", "ns3_s0", "ns4_s0")]
stu = [L("%s/results_res/student_v2%s.jsonl" % (E, s)) for s in ("", "_ns1", "_ns2", "_ns3", "_ns4")]
keys = sorted(pool[0])
mean = lambda D, k: float(np.mean([d[k]["success"] for d in D]))
pb = {k: mean(pool, k) for k in keys}
pd = {k: mean(det, k) for k in keys}
ps = {k: mean(stu, k) for k in keys}
NAMES = ["Soup and sauce in basket", "Cheese and butter in basket", "Stove on, moka pot on stove",
         "Bowl in drawer, close drawer", "Two mugs on plates", "Book in caddy", "Mug on plate, pudding right",
         "Soup and cheese in basket", "Two moka pots on stove", "Mug in microwave, close door"]
rows = []
for t in range(10):
    ks = [k for k in keys if k[0] == t]
    b, d, s = (100 * np.mean([m[k] for k in ks]) for m in (pb, pd, ps))
    rows.append((NAMES[t], b, d, s))
lines = ["% Generated by scripts/table_pertask.py -- do not edit by hand.",
         "\\begin{tabular}{lcccc}", "\\toprule",
         "Task & $\\pi_{0.5}$ & + replan & + student & Gain \\\\", "\\midrule"]
for n, b, d, s in rows:
    lines.append("%s & %.1f & %.1f & %.1f & $%+.1f$ \\\\" % (n, b, d, s, s - b))
b, d, s = (np.mean([r[i] for r in rows]) for i in (1, 2, 3))
lines += ["\\midrule", "Mean & %.1f & %.1f & %.1f & $%+.1f$ \\\\" % (b, d, s, s - b), "\\bottomrule", "\\end{tabular}"]
os.makedirs(os.path.join(OUT, "tables"), exist_ok=True)
open(os.path.join(OUT, "tables", "res_pertask.tex"), "w").write("\n".join(lines) + "\n")

# episode-level and failure analysis
runs = [(k, d[k]) for d in stu for k in keys]
active = lambda r: any(any(abs(v) > 1e-6 for v in q) for q in (r.get("D") or []))
fails = [(k, r) for k, r in runs if not r["success"]]
never = [k for k in keys if pb[k] == 0]
always = [k for k in keys if pb[k] == 1]
diff = np.array([ps[k] - pb[k] for k in keys])
A = {
    "episodes": len(keys), "student_runs": len(runs), "student_fail_runs": len(fails),
    "fail_inactive": sum(1 for k, r in fails if not active(r)),
    "fail_inactive_pct": round(100 * sum(1 for k, r in fails if not active(r)) / len(fails), 1),
    "fail_active_pct": round(100 * sum(1 for k, r in fails if active(r)) / len(fails), 1),
    "base_never": len(never), "student_on_base_never_pct": round(100 * np.mean([ps[k] for k in never]), 1),
    "base_always": len(always), "student_on_base_always_pct": round(100 * np.mean([ps[k] for k in always]), 1),
    "episodes_improved_ge04": int((diff >= 0.4).sum()), "episodes_worsened_ge04": int((diff <= -0.4).sum()),
    "fails_on_base_never_pct": round(100 * sum(1 for k, r in fails if pb[k] == 0) / len(fails), 1),
    "steps_success_student": round(float(np.mean([r["episode_length"] for k, r in runs if r["success"]])), 0),
    "steps_success_base": round(float(np.mean([d[k]["episode_length"] for d in pool for k in keys if d[k]["success"]])), 0),
    "per_task": [{"task": n, "base": round(b, 1), "replan": round(d, 1), "student": round(s, 1)} for n, b, d, s in rows],
}
json.dump(A, open(os.path.join(OUT, "figures", "res_analysis.json"), "w"), indent=1)
print(open(os.path.join(OUT, "tables", "res_pertask.tex")).read())
print(json.dumps({k: v for k, v in A.items() if k != "per_task"}, indent=1))
